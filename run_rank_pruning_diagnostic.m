function [raw_results, summary_results, output_dir] = ...
        run_rank_pruning_diagnostic(output_dir)
%RUN_RANK_PRUNING_DIAGNOSTIC Isolate stopping and pruning at 1e-12.
%   Compares all-level, leaf-only, and disabled pruning for naive reuse and
%   residual-corrected nullspace updates using three matched Poisson seeds.

    if nargin < 1 || isempty(output_dir)
        stamp = char(datetime('now', 'Format', 'yyyyMMdd_HHmmss'));
        output_dir = fullfile(pwd, 'comparison_results', ...
            ['rank_pruning_' stamp]);
    end
    if ~isfolder(output_dir)
        mkdir(output_dir);
    end

    addpath(genpath(fileparts(mfilename('fullpath'))));
    methods = {'naive', 'corrected'};
    pruning_scopes = {'all', 'leaf', 'none'};
    seeds = 0:2;
    rows = struct([]);

    for seed = seeds
        for method_id = 1:numel(methods)
            for scope_id = 1:numel(pruning_scopes)
                method = methods{method_id};
                scope = pruning_scopes{scope_id};
                fprintf('\n=== %s | pruning %s | seed %d ===\n', ...
                    method, scope, seed);
                params = struct( ...
                    'dim', 1, ...
                    'kernel_type', 'poisson_schur', ...
                    'user_tolerance', 1e-12, ...
                    'step_b', 16, ...
                    'num_levels', 5, ...
                    'pt_leaf', 256, ...
                    'method', method, ...
                    'rank_pruning', scope, ...
                    'sample_distribution', 'auto', ...
                    'compute_cond', false, ...
                    'warmup', false, ...
                    'collect_diagnostics', true, ...
                    'comparison_seed', seed);

                rng(seed, 'twister');
                evalc('[~, stats] = main(params);');
                row = stats_to_row(seed, method, scope, stats);
                if isempty(rows)
                    rows = row;
                else
                    rows(end+1) = row; %#ok<AGROW>
                end
            end
        end
    end

    raw_results = struct2table(rows);
    summary_results = summarize_results(raw_results);
    writetable(raw_results, fullfile(output_dir, 'rank_pruning_raw.csv'));
    writetable(summary_results, fullfile(output_dir, ...
        'rank_pruning_summary.csv'));
    save(fullfile(output_dir, 'rank_pruning_diagnostic.mat'), ...
        'raw_results', 'summary_results', 'methods', 'pruning_scopes', ...
        'seeds');
    fprintf('\nSaved rank-pruning diagnostic data to %s\n', output_dir);
end

function row = stats_to_row(seed, method, scope, stats)
    level_stats = stats.level_stats;
    row = struct( ...
        'seed', seed, ...
        'method', string(method), ...
        'pruning_scope', string(scope), ...
        'final_rank', stats.final_rank, ...
        'rank_before_pruning_by_level', ...
            serialize_level_stats(level_stats, 'rank_before_pruning'), ...
        'rank_after_pruning_by_level', ...
            serialize_level_stats(level_stats, 'rank'), ...
        'pruned_count_by_level', ...
            serialize_level_stats(level_stats, 'pruned_count'), ...
        'iterations_by_level', ...
            serialize_level_stats(level_stats, 'iterations'), ...
        'n_matvec', stats.n_matvec, ...
        'nullspace_update_time', stats.nullspace_update_time, ...
        'total_build_time', stats.total_build_time, ...
        'memory_mb', stats.memory_mb, ...
        'operator_probe_error', stats.operator_probe_error, ...
        'solve_residual', stats.solve_residual, ...
        'krylov_iterations', stats.krylov_iterations);
end

function value = serialize_level_stats(level_stats, field)
    tokens = strings(1, numel(level_stats));
    for idx = 1:numel(level_stats)
        tokens(idx) = sprintf('L%d:%g', level_stats(idx).level, ...
            level_stats(idx).(field));
    end
    value = strjoin(tokens, ';');
end

function summary = summarize_results(raw)
    metrics = {'final_rank', 'n_matvec', 'nullspace_update_time', ...
        'total_build_time', 'memory_mb', 'operator_probe_error', ...
        'solve_residual', 'krylov_iterations'};
    summary = unique(raw(:, {'method', 'pruning_scope'}), 'rows');
    for metric_id = 1:numel(metrics)
        metric = metrics{metric_id};
        medians = nan(height(summary), 1);
        minima = nan(height(summary), 1);
        maxima = nan(height(summary), 1);
        for row_id = 1:height(summary)
            select = raw.method == summary.method(row_id) & ...
                raw.pruning_scope == summary.pruning_scope(row_id);
            values = raw.(metric)(select);
            medians(row_id) = median(values);
            minima(row_id) = min(values);
            maxima(row_id) = max(values);
        end
        summary.([metric '_median']) = medians;
        summary.([metric '_min']) = minima;
        summary.([metric '_max']) = maxima;
    end
end
