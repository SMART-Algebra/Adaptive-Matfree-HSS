function [raw_results, summary_results, output_dir] = ...
        run_nullspace_comparison(output_dir, quick_mode, profile)
%RUN_NULLSPACE_COMPARISON Compare four nullspace-update strategies.
%   Runs all four methods with identical RNG seeds and saves raw and aggregated
%   CSV/MAT data. Set quick_mode=true for a small smoke test. The optional
%   profile is 'standard' or 'high_accuracy'.

    if nargin < 1 || isempty(output_dir)
        stamp = char(datetime('now', 'Format', 'yyyyMMdd_HHmmss'));
        output_dir = fullfile(pwd, 'comparison_results', stamp);
    end
    if nargin < 2
        quick_mode = false;
    end
    if nargin < 3 || isempty(profile)
        profile = 'standard';
    end
    profile = lower(char(profile));
    if ~isfolder(output_dir)
        mkdir(output_dir);
    end

    addpath(genpath(fileparts(mfilename('fullpath'))));
    configs = comparison_configs(quick_mode, profile);
    methods = {'naive', 'iterative', 'householder', 'safeguarded', 'corrected'};
    seeds = 0:2;
    checkpoint_file = fullfile(output_dir, 'nullspace_comparison_checkpoint.mat');
    code_commit = code_commit_hash();
    % Resume only a checkpoint this code wrote. One left by other code is
    % set aside together with its CSVs (see load_checkpoint_if_current).
    companions = fullfile(output_dir, {'nullspace_comparison_raw.csv', ...
        'nullspace_comparison_summary.csv', 'nullspace_comparison.mat', ...
        'nullspace_comparison_raw_partial.csv'});
    [saved, resumed] = load_checkpoint_if_current(checkpoint_file, companions);
    if resumed
        rows = saved.rows;
        fprintf('Resuming %d completed runs from %s (code %s)\n', ...
            numel(rows), checkpoint_file, code_commit);
    else
        rows = struct([]);
    end

    for config_id = 1:numel(configs)
        config = configs(config_id);
        for seed = seeds
            for method_id = 1:numel(methods)
                method = methods{method_id};
                if run_is_complete(rows, config_id, seed, method)
                    fprintf('Skipping completed run: %s | %s | seed %d\n', ...
                        config.name, method, seed);
                    continue;
                end
                fprintf('\n=== %s | %s | seed %d ===\n', config.name, method, seed);

                params = struct( ...
                    'dim', config.dim, ...
                    'kernel_type', config.kernel_type, ...
                    'kernel_params', config.kernel_params, ...
                    'user_tolerance', config.tolerance, ...
                    'step_b', config.step_b, ...
                    'num_levels', config.num_levels, ...
                    'pt_leaf', config.pt_leaf, ...
                    'method', method, ...
                    'sample_distribution', 'auto', ...
                    'compute_cond', false, ...
                    'warmup', false, ...
                    'collect_diagnostics', true, ...
                    'comparison_seed', seed);

                % Reset before each method so all consume identical samples.
                rng(seed, 'twister');
                if quick_mode
                    [~, stats] = main(params);
                else
                    evalc('[~, stats] = main(params);');
                end
                row = stats_to_row(config_id, config, seed, stats);
                row.code_commit = string(code_commit);
                if isempty(rows)
                    rows = row;
                else
                    rows(end+1) = row;
                end
                save(checkpoint_file, 'rows', 'configs', 'seeds', 'code_commit');
                writetable(struct2table(rows), ...
                    fullfile(output_dir, 'nullspace_comparison_raw_partial.csv'));
            end
        end
    end

    raw_results = struct2table(rows);
    summary_results = summarize_results(raw_results);
    writetable(raw_results, fullfile(output_dir, 'nullspace_comparison_raw.csv'));
    writetable(summary_results, fullfile(output_dir, 'nullspace_comparison_summary.csv'));
    save(fullfile(output_dir, 'nullspace_comparison.mat'), ...
        'raw_results', 'summary_results', 'configs', 'seeds', 'profile', 'code_commit');
    create_comparison_figure(summary_results, output_dir);
    fprintf('\nSaved comparison data to %s\n', output_dir);
end

function complete = run_is_complete(rows, config_id, seed, method)
    complete = false;
    if isempty(rows)
        return;
    end
    complete = any([rows.config_id] == config_id & [rows.seed] == seed & ...
        string({rows.method}) == string(method));
end

function configs = comparison_configs(quick_mode, profile)
    if quick_mode
        configs = make_config('smoke_1d_poisson', 1, 'poisson_schur', ...
            struct(), 3, 64, 8, 1e-6);
        return;
    end

    template = make_config('', 1, '', struct(), 1, 1, 1, 1);
    configs = repmat(template, 0, 1);
    switch profile
        case 'standard'
            for levels = [5, 7, 9]
                configs(end+1) = make_config( ...
                    sprintf('poisson_1d_L%d', levels), ...
                    1, 'poisson_schur', struct(), levels, 256, 16, 1e-9);
            end
            for tolerance = [1e-3, 1e-6, 1e-9]
                configs(end+1) = make_config( ...
                    sprintf('matern_2d_tol_%s', tolerance_tag(tolerance)), ...
                    2, 'matern', struct('nu', 1.5, 'ell', 0.1), ...
                    4, 256, 32, tolerance);
            end
            for levels = [4, 5]
                configs(end+1) = make_config( ...
                    sprintf('lippmann_schwinger_2d_L%d', levels), ...
                    2, 'helmholtz', struct(), levels, 256, 32, 1e-6);
            end

        case 'high_accuracy'
            configs(end+1) = make_config( ...
                'poisson_1d_L5_tol_1em12', 1, 'poisson_schur', ...
                struct(), 5, 256, 16, 1e-12);
            % Leaf 256, not 64. At 1e-12 a 64-point leaf is smaller than its
            % own off-diagonal numerical rank, so the leaf level exits through
            % the failure branch at full rank without meeting the tolerance
            % (LHS/RHS of order 1e7 for Matern) and every coarser rank is
            % inherited from an uncertified level. See the leaf-size section
            % of README.md.
            configs(end+1) = make_config( ...
                'matern_2d_tol_1em12', 2, 'matern', ...
                struct('nu', 1.5, 'ell', 0.1), 3, 256, 8, 1e-12);
            configs(end+1) = make_config( ...
                'lippmann_schwinger_tol_1em12', ...
                2, 'helmholtz', struct(), 3, 256, 8, 1e-12);

        otherwise
            error(['Unknown comparison profile "%s". Choose ' ...
                '''standard'' or ''high_accuracy''.'], profile);
    end
end

function config = make_config(name, dim, kernel_type, kernel_params, ...
        num_levels, pt_leaf, step_b, tolerance)
    config = struct( ...
        'name', name, ...
        'dim', dim, ...
        'kernel_type', kernel_type, ...
        'kernel_params', kernel_params, ...
        'num_levels', num_levels, ...
        'pt_leaf', pt_leaf, ...
        'step_b', step_b, ...
        'tolerance', tolerance);
end

function row = stats_to_row(config_id, config, seed, stats)
    level_stats = stats.level_stats;
    row = struct( ...
        'config_id', config_id, ...
        'case_name', string(config.name), ...
        'method', string(stats.method), ...
        'rank_pruning', string(stats.rank_pruning), ...
        'sample_distribution', string(stats.sample_distribution), ...
        'seed', seed, ...
        'dim', config.dim, ...
        'kernel_type', string(config.kernel_type), ...
        'n', stats.n, ...
        'num_levels', config.num_levels, ...
        'pt_leaf', config.pt_leaf, ...
        'step_b', config.step_b, ...
        'tolerance', config.tolerance, ...
        'nu', get_param_or_nan(config.kernel_params, 'nu'), ...
        'ell', get_param_or_nan(config.kernel_params, 'ell'), ...
        'final_rank', stats.final_rank, ...
        'rank_by_level', serialize_level_stats(level_stats, 'rank'), ...
        'rank_before_pruning_by_level', ...
            serialize_level_stats(level_stats, 'rank_before_pruning'), ...
        'pruned_count_by_level', ...
            serialize_level_stats(level_stats, 'pruned_count'), ...
        'iterations_by_level', serialize_level_stats(level_stats, 'iterations'), ...
        'nullspace_update_time', stats.nullspace_update_time, ...
        'max_nullspace_residual', stats.max_nullspace_residual, ...
        'max_orthogonality_error', stats.max_orthogonality_error, ...
        'min_initial_rcond', stats.min_initial_rcond, ...
        'safeguard_fallback_count', stats.safeguard_fallback_count, ...
        'n_matvec', stats.n_matvec, ...
        'initial_matvec_count', stats.initial_matvec_count, ...
        'initial_matvec_time', stats.initial_matvec_time, ...
        'adaptive_matvec_time', stats.adaptive_matvec_time, ...
        'total_matvec_time', stats.total_matvec_time, ...
        'matvec_time', stats.t_matvec, ...
        'factorization_time', stats.t_factor, ...
        'factorization_plus_matvec_time', stats.t_factor + stats.t_matvec, ...
        'total_build_time', stats.total_build_time, ...
        'memory_mb', stats.memory_mb, ...
        'solve_time', stats.t_solve, ...
        'solve_residual', stats.solve_residual, ...
        'krylov_iterations', stats.krylov_iterations, ...
        'krylov_relres', stats.krylov_relres, ...
        'unpreconditioned_iterations', stats.unpreconditioned_iterations, ...
        'operator_probe_count', stats.operator_probe_count, ...
        'operator_probe_error', stats.operator_probe_error, ...
        'hss_probe_time', stats.hss_probe_time);
end

function summary = summarize_results(raw)
    metrics = {'final_rank', 'nullspace_update_time', ...
        'max_nullspace_residual', 'max_orthogonality_error', ...
        'min_initial_rcond', 'safeguard_fallback_count', ...
        'n_matvec', 'initial_matvec_count', ...
        'initial_matvec_time', 'adaptive_matvec_time', ...
        'total_matvec_time', 'matvec_time', 'factorization_time', ...
        'factorization_plus_matvec_time', 'total_build_time', ...
        'memory_mb', 'solve_time', 'solve_residual', ...
        'krylov_iterations', 'krylov_relres', ...
        'unpreconditioned_iterations', 'operator_probe_count', ...
        'operator_probe_error', 'hss_probe_time'};
    keys = unique(raw(:, {'config_id', 'case_name', 'method'}), 'rows');
    summary = keys;

    for metric_id = 1:numel(metrics)
        metric = metrics{metric_id};
        median_values = nan(height(keys), 1);
        std_values = nan(height(keys), 1);
        for row_id = 1:height(keys)
            select = raw.config_id == keys.config_id(row_id) & ...
                raw.method == keys.method(row_id);
            values = raw.(metric)(select);
            values = values(isfinite(values));
            if ~isempty(values)
                median_values(row_id) = median(values);
                std_values(row_id) = std(values);
            end
        end
        summary.([metric '_median']) = median_values;
        summary.([metric '_std']) = std_values;
    end
end

function value = get_param_or_nan(params, name)
    if isfield(params, name)
        value = params.(name);
    else
        value = NaN;
    end
end

function value = serialize_level_stats(level_stats, field)
    if isempty(level_stats)
        value = "";
        return;
    end
    tokens = strings(1, numel(level_stats));
    for idx = 1:numel(level_stats)
        tokens(idx) = sprintf('%s:L%d:%g', level_stats(idx).basis, ...
            level_stats(idx).level, level_stats(idx).(field));
    end
    value = strjoin(tokens, ';');
end

function tag = tolerance_tag(tolerance)
    tag = strrep(sprintf('%.0e', tolerance), '-', 'm');
end

function create_comparison_figure(summary, output_dir)
    config_ids = unique(summary.config_id, 'stable');
    num_configs = numel(config_ids);
    methods = ["naive", "iterative", "safeguarded", "corrected"];
    num_methods = numel(methods);
    times = nan(num_configs, num_methods);
    time_std = nan(num_configs, num_methods);
    null_residual = nan(num_configs, num_methods);
    orthogonality = nan(num_configs, num_methods);
    safeguarded_rcond = nan(num_configs, 1);
    labels = strings(num_configs, 1);

    for config_idx = 1:num_configs
        config_id = config_ids(config_idx);
        config_rows = summary.config_id == config_id;
        labels(config_idx) = summary.case_name(find(config_rows, 1));
        for method_idx = 1:num_methods
            row = config_rows & summary.method == methods(method_idx);
            times(config_idx, method_idx) = ...
                summary.factorization_plus_matvec_time_median(row);
            time_std(config_idx, method_idx) = ...
                summary.factorization_plus_matvec_time_std(row);
            null_residual(config_idx, method_idx) = ...
                summary.max_nullspace_residual_median(row);
            orthogonality(config_idx, method_idx) = ...
                summary.max_orthogonality_error_median(row);
        end
        row = config_rows & summary.method == "safeguarded";
        safeguarded_rcond(config_idx) = summary.min_initial_rcond_median(row);
    end

    fig = figure('Visible', 'off', 'Color', 'w', 'Position', [100, 100, 1200, 470]);
    layout = tiledlayout(fig, 1, 2, 'TileSpacing', 'compact', 'Padding', 'compact');

    ax1 = nexttile(layout);
    hold(ax1, 'on');
    x_centers = 1:num_configs;
    offsets = linspace(-0.25, 0.25, num_methods);
    bars = gobjects(1, num_methods);
    for method_idx = 1:num_methods
        x = x_centers + offsets(method_idx);
        bars(method_idx) = bar(ax1, x, times(:, method_idx), 0.24);
        lower_error = min(time_std(:, method_idx), ...
            0.95 * times(:, method_idx));
        errorbar(ax1, x, times(:, method_idx), lower_error, ...
            time_std(:, method_idx), ...
            'k.', 'LineWidth', 0.8, 'CapSize', 4);
    end
    set(ax1, 'YScale', 'log', 'XTick', 1:num_configs, ...
        'XTickLabel', replace(labels, '_', '\_'), 'XTickLabelRotation', 35);
    ylabel(ax1, 'factorization + adaptive matvec time (s)');
    title(ax1, '(a) Runtime');
    legend(ax1, bars, cellstr(methods), 'Location', 'northwest');
    grid(ax1, 'on');

    ax2 = nexttile(layout);
    markers = {'^', 'o', 's', 'd'};
    hold(ax2, 'on');
    stability_lines = gobjects(1, 2*num_methods+1);
    stability_labels = cell(1, 2*num_methods+1);
    for method_idx = 1:num_methods
        stability_lines(method_idx) = semilogy(ax2, 1:num_configs, ...
            null_residual(:, method_idx), [markers{method_idx} '-'], ...
            'LineWidth', 1.1);
        stability_labels{method_idx} = sprintf('null: %s', methods(method_idx));
        stability_lines(num_methods+method_idx) = semilogy(ax2, ...
            1:num_configs, orthogonality(:, method_idx), ...
            [markers{method_idx} '--'], 'LineWidth', 1.1);
        stability_labels{num_methods+method_idx} = ...
            sprintf('orth: %s', methods(method_idx));
    end
    stability_lines(end) = semilogy(ax2, 1:num_configs, safeguarded_rcond, ...
        'd:', 'LineWidth', 1.1);
    stability_labels{end} = 'initial-factor rcond: safeguarded';
    set(ax2, 'YScale', 'log', 'XTick', 1:num_configs, ...
        'XTickLabel', replace(labels, '_', '\_'), 'XTickLabelRotation', 35);
    ylabel(ax2, 'diagnostic value');
    title(ax2, '(b) Numerical stability');
    legend(ax2, stability_lines, stability_labels, ...
        'Location', 'best', 'FontSize', 8);
    grid(ax2, 'on');

    exportgraphics(fig, fullfile(output_dir, 'nullspace_comparison.pdf'), ...
        'ContentType', 'vector');
    exportgraphics(fig, fullfile(output_dir, 'nullspace_comparison.png'), ...
        'Resolution', 200);
    close(fig);
end
