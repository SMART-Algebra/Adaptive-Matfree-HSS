function combined = collect_paper_experiment_results(results_root)
%COLLECT_PAPER_EXPERIMENT_RESULTS Merge checkpointed problem-family tables.
%   COMBINED = COLLECT_PAPER_EXPERIMENT_RESULTS(RESULTS_ROOT) reads every
%   completed */paper_results_raw.csv below RESULTS_ROOT and writes the
%   merged CSV and MAT files to RESULTS_ROOT. It also writes a compact CSV
%   containing every metric used by the manuscript tables and a separate
%   failure table.

    if nargin < 1 || isempty(results_root)
        error(['Give the results root, a directory whose subdirectories ' ...
               'hold paper_results_raw.csv files, for example ' ...
               'comparison_results/stampede3_full_rerun.']);
    end

    files = dir(fullfile(results_root, '*', 'paper_results_raw.csv'));
    if isempty(files)
        error('No problem-family result files found below %s.', results_root);
    end

    tables = cell(numel(files), 1);
    for file_id = 1:numel(files)
        path = fullfile(files(file_id).folder, files(file_id).name);
        tables{file_id} = upgrade_result_table( ...
            read_results_table(path));
    end
    combined = vertcat(tables{:});

    group_order = ["poisson_1d", "poisson_2d", ...
        "matern_low", "matern_high", "lippmann"];
    group_index = zeros(height(combined), 1);
    for group_id = 1:numel(group_order)
        group_index(combined.table_id == group_order(group_id)) = group_id;
    end
    combined.group_order = group_index;
    combined = sortrows(combined, ...
        {'group_order', 'tolerance', 'n'}, {'ascend', 'descend', 'ascend'});
    combined.group_order = [];

    csv_path = fullfile(results_root, 'paper_results_all.csv');
    mat_path = fullfile(results_root, 'paper_results_all.mat');
    writetable(combined, csv_path);
    save(mat_path, 'combined');

    successful = combined(string(combined.status) == "ok", :);
    failed = combined(string(combined.status) ~= "ok", :);
    writetable(successful, ...
        fullfile(results_root, 'paper_results_success.csv'));
    if ~isempty(failed)
        writetable(failed, ...
            fullfile(results_root, 'paper_results_failures.csv'));
    end

    paper_columns = { ...
        'table_id', 'case_name', 'sample_distribution', 'seed', ...
        'tolerance', 'n', 'n1d', 'num_levels', 'pt_leaf', 'step_b', ...
        'final_rank', 'max_rank', 'rank_by_level', ...
        'iterations_by_level', 'root_size', 'n_matvec', ...
        'initial_matvec_count', 'initial_matvec_time', ...
        'adaptive_matvec_time', 'total_matvec_time', ...
        'factorization_time', 'total_build_time', 'solve_time', ...
        'solve_residual', 'factor_storage_mb', 'solver_name', ...
        'solver_flag', 'krylov_iterations', 'krylov_relres', ...
        'unpreconditioned_iterations', ...
        'unpreconditioned_solver_flag', 'wall_seconds', 'hostname', ...
        'slurm_job_id', 'omp_num_threads', 'matlab_version'};
    missing_columns = setdiff(paper_columns, ...
        successful.Properties.VariableNames, 'stable');
    if ~isempty(missing_columns)
        error('Result files are missing paper metric column(s): %s.', ...
            strjoin(missing_columns, ', '));
    end
    paper_metrics = successful(:, paper_columns);
    writetable(paper_metrics, ...
        fullfile(results_root, 'paper_table_metrics.csv'));

    fprintf('Merged %d rows from %d groups into %s\n', ...
        height(combined), numel(files), csv_path);
    fprintf(['Wrote %d successful rows with complete paper metrics; ' ...
        '%d failed rows were kept separately.\n'], ...
        height(successful), height(failed));
end

function table_out = upgrade_result_table(table_in)
%UPGRADE_RESULT_TABLE Supply fields absent from older completed runs.

    table_out = table_in;
    names = table_out.Properties.VariableNames;
    if ~ismember('factor_storage_mb', names)
        table_out.factor_storage_mb = table_out.memory_mb;
    end
    if ~ismember('solver_name', names)
        table_out.solver_name = repmat("PCG", height(table_out), 1);
        table_out.solver_name( ...
            strcmpi(string(table_out.kernel_type), "helmholtz")) = "GMRES";
    end
    if ~ismember('solver_flag', names)
        table_out.solver_flag = nan(height(table_out), 1);
    end
    if ~ismember('unpreconditioned_solver_flag', names)
        table_out.unpreconditioned_solver_flag = ...
            nan(height(table_out), 1);
    end

    canonical_order = { ...
        'config_id', 'table_id', 'case_name', 'status', 'error_message', ...
        'matlab_version', 'hostname', 'slurm_job_id', ...
        'slurm_array_task_id', 'omp_num_threads', 'method', ...
        'sample_distribution', 'seed', 'dim', 'kernel_type', 'n', ...
        'n1d', 'num_levels', 'pt_leaf', 'step_b', 'tolerance', 'nu', ...
        'ell', 'final_rank', 'max_rank', 'rank_by_level', ...
        'iterations_by_level', 'root_size', 'n_matvec', ...
        'initial_matvec_count', 'initial_matvec_time', ...
        'adaptive_matvec_time', 'total_matvec_time', ...
        'factorization_time', 'total_build_time', 'solve_time', ...
        'solve_residual', 'factor_storage_mb', 'memory_mb', ...
        'solver_name', 'solver_flag', 'krylov_iterations', ...
        'krylov_relres', 'unpreconditioned_iterations', ...
        'unpreconditioned_solver_flag', 'wall_seconds'};
    present = intersect(canonical_order, ...
        table_out.Properties.VariableNames, 'stable');
    extras = setdiff(table_out.Properties.VariableNames, present, 'stable');
    table_out = table_out(:, [present, extras]);
end
